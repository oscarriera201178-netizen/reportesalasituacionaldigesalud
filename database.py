import re
import sqlite3
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row


DATABASE_ERRORS = (sqlite3.Error, psycopg.Error)
INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)
TABLES = (
    "centers", "users", "sessions", "quantities", "facilities",
    "facility_counts", "migrated_facilities", "section_loads",
    "vehicle_history", "special_laboratories", "equipment_types",
    "equipment_counts", "plant_counts", "equipment", "military_records", "traffic_records",
)


class SQLiteConnection(sqlite3.Connection):
    def table_columns(self, table):
        return [row["name"] for row in self.execute(f"PRAGMA table_info({table})")]

    def insert_id(self, statement, parameters):
        return self.execute(statement, parameters).lastrowid


class PostgresConnection:
    """Adapt the store's internal SQLite SQL, never interpolating user values."""

    def __init__(self, connection):
        self.raw = connection

    @staticmethod
    def _statement(statement, has_parameters):
        statement = statement.replace(" COLLATE NOCASE", "")
        if "INSERT OR IGNORE INTO" in statement:
            statement = statement.replace("INSERT OR IGNORE INTO", "INSERT INTO")
            statement = statement.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
        if has_parameters:
            statement = statement.replace("%", "%%").replace("?", "%s")
        return statement

    def execute(self, statement, parameters=None):
        return self.raw.execute(self._statement(statement, parameters is not None), parameters)

    def executemany(self, statement, parameters):
        with self.raw.cursor() as cursor:
            cursor.executemany(self._statement(statement, True), parameters)

    def executescript(self, script):
        script = script.replace("TEXT NOT NULL COLLATE NOCASE", "CITEXT NOT NULL")
        script = script.replace("TEXT PRIMARY KEY COLLATE NOCASE", "CITEXT PRIMARY KEY")
        script = script.replace("assigned_username TEXT", "assigned_username CITEXT")
        script = script.replace(" COLLATE NOCASE", "")
        script = re.sub(r"\bid INTEGER PRIMARY KEY", "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", script)
        script = re.sub(r"\bREAL\b", "DOUBLE PRECISION", script)
        script = re.sub(r"\bBLOB\b", "BYTEA", script)
        for statement in script.split(";"):
            if statement.strip():
                self.raw.execute(statement)

    def table_columns(self, table):
        return [
            row["column_name"] for row in self.raw.execute(
                "SELECT column_name FROM information_schema.columns "
                "WHERE table_schema='public' AND table_name=%s ORDER BY ordinal_position",
                (table,),
            )
        ]

    def insert_id(self, statement, parameters):
        return self.execute(statement + " RETURNING id", parameters).fetchone()["id"]

    def is_empty(self):
        for table in TABLES:
            exists = self.raw.execute(
                "SELECT to_regclass(%s) AS relation", (f"public.{table}",),
            ).fetchone()["relation"]
            if exists and self.execute(f"SELECT 1 FROM public.{table} LIMIT 1").fetchone():
                return False
        return True


@contextmanager
def postgres_connection(database_url):
    # The application is the only writer; serialize transactions just as SQLite
    # BEGIN IMMEDIATE does, including permission and weekly-submission checks.
    with psycopg.connect(
        database_url, row_factory=dict_row, connect_timeout=10,
    ) as connection:
        connection.execute("SET LOCAL search_path=public,extensions")
        connection.execute("SET LOCAL statement_timeout=30000")
        connection.execute("SELECT pg_advisory_xact_lock(72401934)")
        yield PostgresConnection(connection)
